DELIMITER //
CREATE DEFINER=`root`@`localhost` PROCEDURE `list_provider_endpoints`(
    IN p_provider_id CHAR(36)
)
BEGIN
    SELECT
        ep.endpoint_id,
        ep.resource_type,
        ep.relative_path,
        ep.http_method,
        ep.description,
        ep.enabled
    FROM api_endpoints ep
    WHERE ep.provider_id = p_provider_id
    ORDER BY ep.resource_type;
END//
